export function localizeAnalytics(
  a: ReturnType<typeof analyze>,
  language: string,
) {
  if (language !== "kk") return a;
  const words: Record<
    string,
    { title: string; fact: string; action: string; limitation: string }
  > = {
    unanswered: {
      title: "Өтініштер жауапсыз қалды",
      fact: `Алғашқы жауабы расталмаған өтініштер: ${a.unanswered}.`,
      action: "Өтініштерді тексеріп, жауаптарды жаңа экспортта тіркеу.",
      limitation:
        "Экспортта жауаптың болмауы клиент жоғалғанын дәлелдемейді. Ықтимал түсім есептелмеген.",
    },
    expenses: {
      title: "Шығындар өсіп жатыр",
      fact: `${money(a.expenses)}; алдыңғы ${a.days} күнде ${money(a.priorExpenses)}.`,
      action:
        "Шығын санаттарын тексеріп, жауапты адамдармен лимиттерді келісу.",
      limitation:
        "Кезеңдер ұзақтығы тең. Маусымдылық пен деректердің толықтығы расталмаған.",
    },
    margin: {
      title: "Жалпы маржа төмен",
      fact: `Жалпы маржа ${a.margin}%. Төленген сатулар мен қайтарулардың өзіндік құны белгілі.`,
      action:
        "Сатып алу бағалары мен жеңілдіктерді тексеру. Өзгерістерді иесімен келісу.",
      limitation:
        "Жалпы пайда таза пайдаға тең емес. Салықтар мен міндеттемелер болмауы мүмкін.",
    },
    overdue: {
      title: "Тапсырмалар кешіктірілді",
      fact: `Мерзімі өткен аяқталмаған тапсырмалар: ${a.overdue}.`,
      action: "Кедергілерді анықтап, жаңа мерзімдерді келісу.",
      limitation: "Тапсырманың аяқталуы қаржылық әсерді растамайды.",
    },
  };
  return {
    ...a,
    insights: a.insights.map((i) => ({ ...i, ...words[i.id] })),
    reviewThemes: a.reviewThemes.map((r) => ({
      ...r,
      name:
        {
          ожидание: "күту",
          качество: "сапа",
          ассортимент: "ассортимент",
          общение: "қарым-қатынас",
        }[r.name] || r.name,
    })),
    formulas: {
      revenue: "Σ төленген сату − Σ төленген қайтару",
      gross: "Түсім − сатудың өзіндік құны + қайтарудың өзіндік құны",
      expenses: "Σ расталған төленген шығындар",
      conversion: "Төлеммен байланысқан өтініш / барлық өтініш × 100%",
      margin: "Жалпы пайда / түсім × 100%",
    },
    forecast: {
      available: false,
      message: "Сенімді болжам үшін деректер жеткіліксіз",
    },
  };
}
