export type AqylAction = keyof typeof aqylActions;
export function isAqylAction(value: unknown): value is AqylAction {
  return typeof value === "string" && Object.hasOwn(aqylActions, value);
}
export function allowedAqylActions(role: string) {
  return (Object.keys(aqylActions) as AqylAction[]).filter(
    (id) =>
      role === "owner" ||
      (!("modal" in aqylActions[id]) &&
        !["business_name", "business_city", "revenue_goal"].includes(id)),
  );
}
