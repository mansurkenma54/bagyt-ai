import type { analyze } from "./analytics";
import { money } from "./types";
export type GuideLanguage = "ru" | "kk";
export type GuideAnswer = {
  text: string;
  destination?: string;
  label?: string;
};
export type GuideAnalytics = ReturnType<typeof analyze>;
export function answerGuide(
  question: string,
  language: GuideLanguage,
  a?: GuideAnalytics,
): GuideAnswer | null {
  const t = (r: string, k: string) => (language === "ru" ? r : k);
  const q = question.toLowerCase().trim();
  const link = (text: string, destination: string, label: string) => ({
    text,
    destination,
    label,
  });
  if (/привет|сәлем|салам|здравств/.test(q))
    return {
      text: t(
        "Сәлем! Я рядом. Хотите разобраться с данными, узнать о продажах или найти нужную кнопку?",
        "Сәлем! Мен қасыңыздамын. Деректерді түсінгіңіз, сатуды көргіңіз немесе керекті батырманы тапқыңыз келе ме?",
      ),
    };
  if (
    /ватсап|whatsapp|инст|instagram|тикток|tiktok|umag|умаг|2gis|2гис|синхрон/.test(
      q,
    )
  )
    return link(
      t(
        "Пока можно загрузить выгрузку Excel/CSV. Подключения соцсетей по номеру и ссылке демонстрационные: сообщения сами не загружаются. Для синхронизации нужен официальный API сервиса.",
        "Әзірге Excel/CSV есебін жүктеуге болады. Нөмір мен сілтеме арқылы әлеуметтік желіні қосу — демо: хабарлар өздігінен жүктелмейді. Синхрондау үшін сервистің ресми API-і керек.",
      ),
      "connect",
      t("Посмотреть источники", "Дереккөздерді көру"),
    );
  if (/нача|баста|регист|тіркел|аккаунт/.test(q))
    return link(
      t(
        a
          ? "Аккаунт уже готов. Начните с одной таблицы или чека в «Мои данные». Проверьте распознанные записи — после подтверждения я пересчитаю показатели."
          : "Сначала познакомимся: выберите свой бизнес, цель и создайте аккаунт. Потом добавим таблицу или чек. Я останусь рядом и покажу каждый шаг.",
        a
          ? "Аккаунт дайын. «Деректерім» бетінде бір кесте немесе чектен бастаңыз. Жазбаларды тексеріп растаған соң көрсеткіштерді қайта есептеймін."
          : "Алдымен танысамыз: бизнесіңізді, мақсатыңызды таңдап, аккаунт құрыңыз. Содан кейін кесте немесе чек қосамыз. Әр қадамда көмектесемін.",
      ),
      a ? "connect" : "register",
      t(
        a ? "Добавить данные" : "Начать знакомство",
        a ? "Дерек қосу" : "Танысуды бастау",
      ),
    );
  if (/данн|дерек|таблиц|excel|csv|загруз|жүкт|чек|провер|тексер/.test(q))
    return link(
      t(
        a
          ? `Подтверждено ${a.coverage.verified} записей; на проверке ${a.coverage.pending}. В «Мои данные» загрузите Excel/CSV или фото чека. Проверьте дату, тип и сумму перед подтверждением. Дубликаты в расчёт не входят.`
          : "В «Мои данные» можно загрузить Excel/CSV, фото чека или добавить запись вручную. Анализ появится после проверки записей.",
        a
          ? `${a.coverage.verified} жазба расталды; ${a.coverage.pending} жазба тексеруді күтеді. «Деректерім» бетіне Excel/CSV немесе чек фотосын жүктеңіз. Растамас бұрын күнін, түрін және сомасын тексеріңіз. Қайталанған жазбалар есепке кірмейді.`
          : "«Деректерім» бетінде Excel/CSV, чек фотосын немесе қолмен жазба қоса аласыз. Талдау жазбалар тексерілген соң пайда болады.",
      ),
      a ? "connect" : "register",
      t(
        a ? "Открыть мои данные" : "Создать аккаунт",
        a ? "Деректерімді ашу" : "Аккаунт құру",
      ),
    );
  if (/продаж|выруч|расход|прибы|сандар|түсім|сату|шығын|прибыл/.test(q)) {
    if (!a?.coverage.verified)
      return link(
        t(
          "Пока нет подтверждённых записей для расчёта. Добавьте свои данные — тогда смогу показать выручку и расходы.",
          "Есептеу үшін расталған жазбалар әзірге жоқ. Деректеріңізді қосыңыз — түсім мен шығындарды көрсете аламын.",
        ),
        a ? "connect" : "register",
        t("Добавить данные", "Дерек қосу"),
      );
    return link(
      t(
        `За выбранный период выручка ${money(a.revenue)}, расходы ${money(a.expenses)}. В расчёте ${a.coverage.verified} подтверждённых записей. Это только добавленные данные, а не весь оборот бизнеса.`,
        `Таңдалған кезеңдегі түсім ${money(a.revenue)}, шығындар ${money(a.expenses)}. Есепке ${a.coverage.verified} расталған жазба кірді. Бұл бизнестің толық айналымы емес, тек қосылған деректер.`,
      ),
      "overview",
      t("Посмотреть показатели", "Көрсеткіштерді көру"),
    );
  }
  if (/план|дела|задач|совет|внима|жоспар|кеңес|не істе|что дел|важн/.test(q))
    return link(
      t(
        a?.coverage.verified
          ? `Начните с разбора BELGI AI: ${a.insights.length} сигналов по проверенным данным. Откройте объяснение и исходные записи. В «Мои дела» можно составить план и утвердить подходящие действия.`
          : "Первый полезный шаг — добавить таблицу или чек. Без ваших данных я не буду угадывать, что происходит в бизнесе.",
        a?.coverage.verified
          ? `BELGI AI талдауынан бастаңыз: тексерілген деректер бойынша ${a.insights.length} белгі бар. Түсіндірме мен бастапқы жазбаларды қараңыз. «Істерім» бетінде жоспар құрып, әрекеттерді бекіте аласыз.`
          : "Алғашқы пайдалы қадам — кесте немесе чек қосу. Деректерсіз бизнестің жағдайын болжай алмаймын.",
      ),
      a?.coverage.verified ? "insights" : a ? "connect" : "register",
      t("Показать следующий шаг", "Келесі қадамды көрсету"),
    );
  if (/клиент|обращ|өтініш/.test(q))
    return link(
      t(
        a
          ? `В добавленных данных ${a.leads} обращений; ${a.unanswered} без подтверждённого первого ответа. Откройте разбор, чтобы увидеть исходные записи.`
          : "Обращения клиентов появятся после добавления данных. BELGI AI покажет обращения без подтверждённого ответа.",
        a
          ? `Қосылған деректерде ${a.leads} өтініш бар; ${a.unanswered} өтініштің алғашқы жауабы расталмаған. Бастапқы жазбаларды талдаудан көріңіз.`
          : "Клиенттердің өтініштері деректерді қосқаннан кейін көрінеді. BELGI AI жауабы расталмаған өтініштерді көрсетеді.",
      ),
      a ? "insights" : "register",
      t("Посмотреть", "Көру"),
    );
  if (/настро|баптау|команд|профил/.test(q))
    return link(
      t(
        "В «Настройки» находятся сведения о бизнесе, цель и команда. Доступ к изменениям зависит от вашей роли.",
        "«Баптаулар» бетінде бизнес туралы ақпарат, мақсат және команда бар. Өзгерту мүмкіндігі рөліңізге байланысты.",
      ),
      a ? "settings" : "register",
      t("Открыть", "Ашу"),
    );
  if (/результ|нәтиже/.test(q))
    return link(
      t(
        "В «Результаты» сравниваются показатели до и после выполненных действий. Для проверки нужны данные обоих периодов; рост заранее не обещаю.",
        "«Нәтижелер» бетінде әрекетке дейінгі және кейінгі көрсеткіштер салыстырылады. Тексеру үшін екі кезеңнің де деректері қажет; өсімге алдын ала уәде бермеймін.",
      ),
      a ? "results" : "register",
      t("Посмотреть результаты", "Нәтижелерді көру"),
    );
  return null;
}

